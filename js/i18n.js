  function current() {
    try { return localStorage.getItem("zh-lang") || "ru"; } catch (e) { return "ru"; }
  }

  function t(key, fallback) {
    var lang = current();
    var pack = dict[lang] || dict.ru || {};
    return pack[key] != null ? pack[key] : (fallback || key);
  }

  function apply(lang) {
    if (!dict[lang]) lang = "ru";
    try { localStorage.setItem("zh-lang", lang); } catch (e) {}
    document.documentElement.lang = lang === "hy" ? "hy" : lang === "en" ? "en" : "ru";
    document.documentElement.classList.remove("i18n-pending");
    var pack = dict[lang] || dict.ru;
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (pack[key] != null) el.textContent = pack[key];
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-placeholder");
      if (pack[key] != null) el.setAttribute("placeholder", pack[key]);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-aria");
      if (pack[key] != null) el.setAttribute("aria-label", pack[key]);
    });
    document.querySelectorAll("[data-lang]").forEach(function (btn) {
      btn.classList.toggle("is-active", btn.getAttribute("data-lang") === lang);
    });
    if (pack["bk.adminTitle"]) document.title = pack["bk.adminTitle"] + " — Kennel Booking";
  }

  function setLang(lang) {
    try { localStorage.setItem("zh-lang", lang); } catch (e) {}
    apply(lang);
  }

  window.ZH = { dict: dict, apply: apply, setLang: setLang, current: current, t: t };

  document.addEventListener("DOMContentLoaded", function () {
    apply(current());
    document.querySelectorAll("[data-lang]").forEach(function (btn) {
      btn.addEventListener("click", function () {
        setLang(btn.getAttribute("data-lang"));
      });
    });
  });
